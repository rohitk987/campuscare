function greedy(jobs, techs, o = ASSIGNMENT) {
 const used = new Map(techs.map(t => [t.id, 0])); let total = 0;
 for (const job of [...jobs].sort((a, b) => (b.priority || 0) - (a.priority || 0))) {
  const bestAff = Math.max(1e-9, ...techs.map(t => categoryAffinity(t, job.category)));
  let choice = null, cost = o.unassignedCost;
  for (const t of techs) { const k = used.get(t.id); if (k >= o.capacity) continue; const c = o.loadWeight * Math.min(1, (t.load + k) / (2 * o.capacity)) + o.skillWeight * (1 - categoryAffinity(t, job.category) / bestAff); if (c < cost) { cost = c; choice = t; } }
  if (choice) used.set(choice.id, used.get(choice.id) + 1);
  total += cost;
 }
 return total;
}
